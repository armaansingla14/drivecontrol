"""Closed-loop simulation: C++ controller (via ctypes) + Python vehicle model."""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Optional

import numpy as np

from . import bridge
from .tracks import Track
from .vehicle import Bicycle, VehicleParams

DT = 0.01  # controller period (100 Hz)
END_ZONE = 5.0  # m before the path end: stopping zone, excluded from tracking metrics


class FastProjector:
    """Windowed nearest-segment search (numpy) used to measure tracking errors
    independently of the controller's own projection."""

    def __init__(self, x: np.ndarray, y: np.ndarray, v: np.ndarray):
        self.x, self.y, self.v = np.asarray(x, float), np.asarray(y, float), np.asarray(v, float)
        self.s = np.concatenate([[0.0], np.cumsum(np.hypot(np.diff(self.x), np.diff(self.y)))])
        self.hint = None

    def project(self, px: float, py: float, window: int = 200):
        n = len(self.x) - 1
        lo, hi = (0, n) if self.hint is None else (max(0, self.hint - window), min(n, self.hint + window))
        ax, ay = self.x[lo:hi], self.y[lo:hi]
        dx, dy = self.x[lo + 1:hi + 1] - ax, self.y[lo + 1:hi + 1] - ay
        l2 = dx * dx + dy * dy
        t = np.clip(((px - ax) * dx + (py - ay) * dy) / np.where(l2 > 0, l2, 1.0), 0.0, 1.0)
        qx, qy = ax + t * dx, ay + t * dy
        d2 = (px - qx) ** 2 + (py - qy) ** 2
        if self.hint is None:  # global search: earliest local minimum within 0.5 m of the best
            lim = (math.sqrt(d2.min()) + 0.5) ** 2
            left = np.concatenate([[np.inf], d2[:-1]])
            right = np.concatenate([d2[1:], [np.inf]])
            ok = (d2 <= left) & (d2 <= right) & (d2 <= lim)
            k = int(np.argmax(ok))
        else:
            k = int(np.argmin(d2))
        i = lo + k
        self.hint = i
        yaw = math.atan2(dy[k], dx[k])
        cross = math.cos(yaw) * (py - qy[k]) - math.sin(yaw) * (px - qx[k])
        e = math.copysign(math.sqrt(d2[k]), cross)
        s = self.s[i] + t[k] * (self.s[i + 1] - self.s[i])
        v_ref = self.v[i] + t[k] * (self.v[i + 1] - self.v[i])
        return s, yaw, e, v_ref


@dataclass
class CanScript:
    """Traffic generated by the planner (DC_Command, 50 ms) and the safety
    controller (DC_EStop heartbeat, 20 ms)."""

    target_speed: float = 60.0
    estop_at: Optional[float] = None          # e-stop bit set from this time
    heartbeat_stop_at: Optional[float] = None  # safety controller goes silent
    command_stop_at: Optional[float] = None    # planner goes silent
    corrupt_from: Optional[float] = None       # frames sent with a broken CRC in [from, to)
    corrupt_to: Optional[float] = None


@dataclass
class RunLog:
    t: list = field(default_factory=list)
    x: list = field(default_factory=list)
    y: list = field(default_factory=list)
    v: list = field(default_factory=list)
    v_ref: list = field(default_factory=list)
    lat_err: list = field(default_factory=list)
    head_err: list = field(default_factory=list)
    steer_cmd: list = field(default_factory=list)
    throttle: list = field(default_factory=list)
    brake: list = field(default_factory=list)
    steer_act: list = field(default_factory=list)
    ax: list = field(default_factory=list)
    ay: list = field(default_factory=list)
    state: list = field(default_factory=list)
    s: list = field(default_factory=list)
    completed: bool = False

    def arrays(self):
        return {k: np.asarray(v) for k, v in self.__dict__.items() if isinstance(v, list)}


def run(track: Track, controller: str = "stanley", dynamic: bool = True, anti_windup: str = "backcalc",
        can: Optional[CanScript] = None, t_max: float = 400.0, v0: float = 0.0,
        stop_on: Optional[str] = None, params: Optional[VehicleParams] = None, **overrides) -> RunLog:
    """Run one closed-loop simulation.

    stop_on: None -> until end of track; "standstill" -> stop when the car has
    come to rest after a stop was triggered.
    """
    ctrl = bridge.Controller(controller, use_can=can is not None, anti_windup=anti_windup, **overrides)
    ctrl.set_path(track.x, track.y, track.v)
    car = Bicycle(p=params or VehicleParams(), dynamic=dynamic)
    yaw0 = math.atan2(track.y[1] - track.y[0], track.x[1] - track.x[0])
    car.reset(track.x[0], track.y[0], yaw0, v0)
    proj = FastProjector(track.x, track.y, track.v)
    log = RunLog()
    p = car.p
    ctr_cmd = ctr_es = 0
    length = track.length
    t = 0.0
    stop_triggered = False
    try:
        while t < t_max:
            if can is not None:
                corrupt = can.corrupt_from is not None and can.corrupt_from <= t < (can.corrupt_to or 1e9)
                k = int(round(t / DT))
                if k % 2 == 0 and (can.heartbeat_stop_at is None or t < can.heartbeat_stop_at):
                    data = bytearray(bridge.encode_estop(can.estop_at is not None and t >= can.estop_at, ctr_es))
                    ctr_es += 1
                    if corrupt:
                        data[7] ^= 0x5A
                    ctrl.can_rx(bridge.ID_ESTOP, bytes(data), t)
                if k % 5 == 0 and (can.command_stop_at is None or t < can.command_stop_at):
                    data = bytearray(bridge.encode_command(can.target_speed, True, False, ctr_cmd))
                    ctr_cmd += 1
                    if corrupt:
                        data[7] ^= 0x5A
                    ctrl.can_rx(bridge.ID_COMMAND, bytes(data), t)
            st = car.st
            rx, ry = car.rear_axle()
            steer, thr, brk = ctrl.step(rx, ry, st.psi, st.vx, st.delta, st.r, t, DT)
            dbg = ctrl.debug()
            ctrl.can_tx()  # drain the TX queue (frames not needed here)
            s_cg, yaw_p, e_cg, v_ref = proj.project(st.X, st.Y)
            log.t.append(t)
            log.x.append(st.X)
            log.y.append(st.Y)
            log.v.append(st.vx)
            log.v_ref.append(v_ref)
            log.lat_err.append(e_cg)
            log.head_err.append(math.atan2(math.sin(yaw_p - st.psi), math.cos(yaw_p - st.psi)))
            log.steer_cmd.append(steer)
            log.throttle.append(thr)
            log.brake.append(brk)
            log.steer_act.append(st.delta)
            log.ax.append(st.ax)
            log.ay.append(st.vx * st.r)
            log.state.append(dbg.state)
            log.s.append(s_cg)
            if dbg.state in (2, 3) or (controller == "naive" and brk > 0.99):
                stop_triggered = True
            if stop_on == "standstill" and stop_triggered and st.vx < 0.05:
                break
            if track.grade is not None:
                car.grade = track.grade(st.s_travel)
            car.step(steer, thr, brk, DT)
            t += DT
            if s_cg > length - END_ZONE and st.vx < 0.3:
                log.completed = True
                break
    finally:
        ctrl.close()
    return log


# ----------------------------------------------------------------------------- metrics

def tracking_metrics(log: RunLog, limits: dict) -> dict:
    a = log.arrays()
    length = a["s"].max() if a["s"].size else 0.0
    # exclude samples beyond the path end, where the projection clamps to the last point
    active = (a["state"] == 1) & (a["s"] < length - END_ZONE)
    lat = a["lat_err"][active]
    head = a["head_err"][active]
    verr = (a["v"] - a["v_ref"])[active]
    c = constraint_violations(log, limits)
    return {
        "lat_rms": float(np.sqrt(np.mean(lat ** 2))) if lat.size else float("nan"),
        "lat_max": float(np.max(np.abs(lat))) if lat.size else float("nan"),
        "head_rms_deg": float(np.degrees(np.sqrt(np.mean(head ** 2)))) if head.size else float("nan"),
        "speed_rms": float(np.sqrt(np.mean(verr ** 2))) if verr.size else float("nan"),
        "ay_max": float(np.max(np.abs(a["ay"]))),
        "completed": bool(log.completed),
        "duration_s": float(a["t"][-1]) if a["t"].size else 0.0,
        **c,
    }


def constraint_violations(log: RunLog, limits: dict) -> dict:
    """Commanded outputs checked against the actuator limits of the vehicle
    interface: steering range and rate, pedal range and apply rates, and
    throttle/brake exclusivity."""
    a = log.arrays()
    n = len(a["t"])
    if n < 2:
        return {"viol_steer_range": 0, "viol_steer_rate": 0, "viol_pedal_rate": 0, "viol_overlap": 0, "steps": n}
    eps = 1e-6
    steer = a["steer_cmd"]
    d_steer = np.abs(np.diff(steer)) / DT
    d_thr = np.diff(a["throttle"]) / DT
    d_brk = np.diff(a["brake"]) / DT
    estop = a["state"][1:] == 3
    brk_lim = np.where(estop, limits["estop_brake_rate"], limits["brake_rate_up"])
    return {
        "viol_steer_range": int(np.sum(np.abs(steer) > limits["steer_max"] + eps)),
        "viol_steer_rate": int(np.sum(d_steer > limits["steer_rate_max"] * (1 + 1e-6) + eps)),
        "viol_pedal_rate": int(np.sum(d_thr > limits["throttle_rate_up"] * (1 + 1e-6) + eps)
                               + np.sum(d_brk > brk_lim * (1 + 1e-6) + eps)),
        "viol_overlap": int(np.sum((a["throttle"] > eps) & (a["brake"] > eps))),
        "steps": n,
    }


LIMITS = {"steer_max": 0.52, "steer_rate_max": 0.6, "throttle_rate_up": 1.5, "brake_rate_up": 4.0,
          "estop_brake_rate": 10.0}
